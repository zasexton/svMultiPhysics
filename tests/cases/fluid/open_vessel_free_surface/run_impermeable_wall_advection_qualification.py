#!/usr/bin/env python3
"""Qualify P1 level-set advection of moving contact points on impermeable walls.

This is a production ApplicationDriver/TimeLoop transport-isolation gate.  A
vertical P1 interface is advected by the prescribed divergence-free velocity
generated by ``psi=A*x*(1-x/L)*y*(H-y)``.  All four walls are closed and have
identically zero normal velocity.  The bottom and top contact points move in
opposite tangential directions, while wall vertices ahead of the interface
remain exactly dry.  Backward RK4 characteristics supply the reference field;
no scalar inflow condition or open-boundary shortcut is used.

The gate does not exercise the Navier--Stokes momentum or contact-line force
operators and must not be reported as a dynamic-wetting benchmark.

The profile records strict one-ring excursions but permits an explicitly
capped qualification-scale numerical slack for the non-DMP spatial operator.
That slack does not alter the independent sign, false-wet, accuracy, contact,
or refinement gates and is not an invariant-domain certification.
"""

from __future__ import annotations

import argparse
import json
