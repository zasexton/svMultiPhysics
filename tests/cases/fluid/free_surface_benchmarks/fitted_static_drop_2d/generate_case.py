def generate(level: int, output_dir: Path, *, end_time: float = END_TIME,
             force: bool = False) -> dict:
    if level not in LEVELS:
        raise ValueError(f"--level must be one of {LEVELS}")
    if output_dir.exists() and any(output_dir.iterdir()) and not force:
        raise FileExistsError(f"{output_dir} is not empty (use --force)")
    steps = int(round(end_time / DT))
    points, cells, boundary, parents = disk_mesh(level)
    n = points.shape[0]
    mesh_dir = output_dir / "mesh"
    (mesh_dir / "mesh-surfaces").mkdir(parents=True, exist_ok=True)
    zeros3 = np.zeros((n, 3))
    LS.write_vtu(mesh_dir / "mesh-complete.mesh.vtu", points, cells,
                 {"GlobalNodeID": ("Int64", np.arange(n)),
                  "Velocity": ("Float64", zeros3),
                  "Pressure": ("Float64", np.full(n, SURFACE_TENSION / RADIUS)),
                  "mesh_displacement": ("Float64", zeros3),
                  "mesh_velocity": ("Float64", zeros3)},
                 {"GlobalElementID": ("Int64", np.arange(cells.shape[0]))})
    LS.write_face_vtp(mesh_dir / "mesh-surfaces" / f"{FREE_SURFACE}.vtp", points,
                      boundary, parents)
    (output_dir / "solver.xml").write_text(solver_xml(steps), encoding="utf-8")
    sides = 6 * level
    area = polygon_area(points, cells)
    case = {
        "benchmark": "fitted_static_drop_2d",
        "generator": "tests/cases/fluid/free_surface_benchmarks/fitted_static_drop_2d/generate_case.py",
        "level_rings": level,
        "boundary_sides": sides,
        "n_vertices": int(n),
        "n_triangles": int(cells.shape[0]),
        "free_surface_nodes": [int(v) for v in boundary[:-1]],
        "density": DENSITY,
        "surface_tension": SURFACE_TENSION,
        "radius": RADIUS,
        "viscosity": VISCOSITY,
        "laplace_number": LAPLACE_NUMBER,
        "viscous_time": DENSITY * RADIUS ** 2 / VISCOSITY,
        "initial_area": area,
        "effective_radius": math.sqrt(area / math.pi),
        "pressure_laplace": SURFACE_TENSION / RADIUS,
        "pressure_regular_polygon_balance": SURFACE_TENSION / (RADIUS * math.cos(math.pi / sides)),
        "dt": DT,
        "steps": steps,
        "end_time": steps * DT,
        "output_cadence": min(OUTPUT_CADENCE, steps),
        "velocity_field": "Velocity",
        "pressure_field": "Pressure",
        "displacement_field": "mesh_displacement",
        "result_prefix": "result",
    }
    (output_dir / "case.json").write_text(json.dumps(case, indent=2) + "\n", encoding="utf-8")
    return case


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--level", type=int, required=True, choices=LEVELS,
                        help="R/h = number of node rings")
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--end-time", type=float, default=END_TIME)
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args(argv)
    case = generate(args.level, args.output_dir, end_time=args.end_time, force=args.force)
    print(f"wrote {args.output_dir}")
    for key in ("level_rings", "boundary_sides", "n_vertices", "n_triangles", "effective_radius",
                "pressure_regular_polygon_balance", "dt", "steps"):
        print(f"  {key} = {case[key]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
