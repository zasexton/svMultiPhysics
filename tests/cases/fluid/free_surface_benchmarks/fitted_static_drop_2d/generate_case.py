#!/usr/bin/env python3
"""Write one level of the 2D fitted-ALE static-drop smoke case (tracker M5, decision D5).

A closed 2D liquid drop bounded by a fitted free surface, zero gravity, with
the opt-in fitted SurfaceStress (Laplace-Beltrami) capillary form.  The drop
starts from the sampled circle at rest with the uniform pressure gamma/R and
relaxes; the smoke run reports the pressure jump against gamma/R and the
spurious velocity (README.md).

The case is written for the new OOP solver: solver.xml, the disk mesh with
the initial fields, the free-surface face file, and case.json.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import math
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent


def _load(directory: str, name: str):
    path = HERE.parent / directory / f"{name}.py"
    spec = importlib.util.spec_from_file_location(f"{directory}_{name}", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


LS = _load("linear_sloshing_2d", "generate_case")      # VTU/VTP writers

# ---------------------------------------------------------------------------
# Constants, fixed for every level (principle P1).  Physical values follow
# static_drop_2d (rho = gamma = R = 1, La = 12); README.md gives the reasons.
# ---------------------------------------------------------------------------
LEVELS = (8, 16, 32)                        # R/h = number of node rings
DENSITY = 1.0
SURFACE_TENSION = 1.0
RADIUS = 1.0
LAPLACE_NUMBER = 12.0
VISCOSITY = math.sqrt(2.0 / LAPLACE_NUMBER)  # mu = sqrt(rho gamma 2R / La) = 0.4082
DT = 0.01                                   # capillary time sqrt(rho R^3 / gamma) = 1
END_TIME = 1.0
OUTPUT_CADENCE = 10
MESH_MOTION_KAPPA = 1.0
KINEMATIC_NITSCHE_GAMMA = 10.0              # as fitted_sloshing_2d
FREE_SURFACE = "free_surface"


def disk_mesh(rings: int, radius: float = RADIUS):
    """Hexagonal ring triangulation of the disk: ring i (i = 1..rings) at
    radius i R/rings carries 6 i equally spaced nodes, so the free surface is
    the regular 6 rings-gon inscribed in the circle."""
    points = [(0.0, 0.0)]
    ring_start = [0]
    for i in range(1, rings + 1):
        ring_start.append(len(points))
        r = radius * i / rings
        for j in range(6 * i):
            theta = 2.0 * math.pi * j / (6 * i)
            points.append((r * math.cos(theta), r * math.sin(theta)))
    points = np.array([(x, y, 0.0) for x, y in points])

    def node(i: int, j: int) -> int:
        if i == 0:
            return 0
        return ring_start[i] + (j % (6 * i))

    cells = []
    for i in range(1, rings + 1):
        # Between ring i-1 (6(i-1) nodes) and ring i (6 i nodes): six sectors
        # of i outer edges each.
        for sector in range(6):
            for k in range(i):
                outer_a = node(i, sector * i + k)
                outer_b = node(i, sector * i + k + 1)
                inner_a = node(i - 1, sector * (i - 1) + k)
                cells.append((inner_a, outer_a, outer_b))
                if k < i - 1:
                    inner_b = node(i - 1, sector * (i - 1) + k + 1)
                    cells.append((inner_a, outer_b, inner_b))
    cells = np.asarray(cells, dtype=np.int64)
    # Orient counter-clockwise.
    p = points[cells][:, :, :2]
    signed = (p[:, 1, 0] - p[:, 0, 0]) * (p[:, 2, 1] - p[:, 0, 1]) - \
             (p[:, 1, 1] - p[:, 0, 1]) * (p[:, 2, 0] - p[:, 0, 0])
    cells[signed < 0] = cells[signed < 0][:, [0, 2, 1]]
    boundary = [node(rings, j) for j in range(6 * rings)] + [node(rings, 0)]
    # Parent cell of each boundary edge (outer_a, outer_b).
    parent_of = {}
    for c, (a, b, cc) in enumerate(cells):
        for u, v in ((a, b), (b, cc), (cc, a)):
            parent_of[(min(u, v), max(u, v))] = c
    parents = [parent_of[(min(u, v), max(u, v))] for u, v in zip(boundary[:-1], boundary[1:])]
    return points, cells, boundary, parents


def polygon_area(points: np.ndarray, cells: np.ndarray) -> float:
    p = points[cells][:, :, :2]
    e1, e2 = p[:, 1] - p[:, 0], p[:, 2] - p[:, 0]
    return float(0.5 * np.sum(np.abs(e1[:, 0] * e2[:, 1] - e1[:, 1] * e2[:, 0])))


